@pytest.fixture(scope="module")
def engine() -> Iterator[Engine]:
    # Own database, not the shared db_url: these tests downgrade to base.
    with throwaway_db() as url:
        test_engine = create_engine(url)
        try:
            yield test_engine
        finally:
            test_engine.dispose()


@pytest.fixture
def conn(engine: Engine) -> Iterator[Connection]:
    with engine.connect() as connection, connection.begin() as trans:
        yield connection
        trans.rollback()


def insert_chain(conn: Connection, table: str, kind: str = "user") -> dict[str, uuid.UUID]:
    """Insert a row into `table` and every parent it needs; return each new id by table."""
    parent = PARENT.get(table)
    ids = insert_chain(conn, parent, OWNER_KIND.get(table, kind)) if parent else {}
    params = {"parent": ids[parent]} if parent else {"kind": kind}
    ids[table] = conn.execute(text(ROW_SQL[table] + " RETURNING id"), params).scalar_one()
    return ids


def parent_params(conn: Connection, table: str) -> dict[str, uuid.UUID]:
    parent = PARENT.get(table)
    if not parent:
        return {}
    return {"parent": insert_chain(conn, parent, OWNER_KIND.get(table, "user"))[parent]}


def test_downgrade_base_then_upgrade_head(engine: Engine) -> None:
    cfg = alembic_config(engine.url.render_as_string(hide_password=False))
    command.downgrade(cfg, "base")
    assert inspect(engine).get_table_names() == ["alembic_version"]
    command.upgrade(cfg, "head")
    assert set(inspect(engine).get_table_names()) == {"alembic_version", *Base.metadata.tables}


def test_models_match_migrations_and_unmodelled_tables_are_ignored(engine: Engine) -> None:
    with engine.begin() as connection:
        connection.execute(text("CREATE TABLE langgraph_stub (id int)"))
    try:
        # Raises AutogenerateDiffsDetected on drift, including server defaults.
        command.check(alembic_config(engine.url.render_as_string(hide_password=False)))
    finally:
        with engine.begin() as connection:
            connection.execute(text("DROP TABLE langgraph_stub"))


def test_server_defaults(conn: Connection) -> None:
    document = conn.execute(
        text(ROW_SQL["documents"] + " RETURNING status, attempts, run_after, created_at"),
        parent_params(conn, "documents"),
    ).one()
    assert (document.status, document.attempts) == ("pending", 0)
    assert document.run_after is not None and document.created_at is not None

    message = conn.execute(
        text(ROW_SQL["messages"] + " RETURNING citations, created_at"),
        parent_params(conn, "messages"),
    ).one()
    assert message.citations == [] and message.created_at is not None


@pytest.mark.parametrize(("constraint", "table", "sql"), UNIQUES, ids=[c for c, *_ in UNIQUES])
def test_unique_rejects_duplicate(conn: Connection, constraint: str, table: str, sql: str) -> None:
    conn.execute(text(sql), parent_params(conn, table))
    params = parent_params(conn, table)
    with pytest.raises(IntegrityError) as exc:
        conn.execute(text(sql), params)
    assert exc.value.orig.diag.constraint_name == constraint  # type: ignore[union-attr]


@pytest.mark.parametrize(
    ("constraint", "table", "sql", "bad"),
    [(c, t, s, bad) for c, t, s, bads, _ in CHECKS for bad in bads],
)
def test_check_rejects_bad_row(
    conn: Connection, constraint: str, table: str, sql: str, bad: str | None
) -> None:
    params = parent_params(conn, table)
    with pytest.raises(IntegrityError) as exc:
        conn.execute(text(sql), {**params, "v": bad})
    assert exc.value.orig.diag.constraint_name == constraint  # type: ignore[union-attr]


@pytest.mark.parametrize(
    ("table", "sql", "good"),
    [(t, s, good) for _, t, s, _, good in CHECKS],
    ids=[c for c, *_ in CHECKS],
)
def test_check_accepts_valid_row(conn: Connection, table: str, sql: str, good: str) -> None:
    conn.execute(text(sql), {**parent_params(conn, table), "v": good})


@pytest.mark.parametrize("child", ["documents", "chats"])
def test_owner_delete_is_restricted_by(conn: Connection, child: str) -> None:
    ids = insert_chain(conn, child)
    with pytest.raises(IntegrityError) as exc:
        conn.execute(text("DELETE FROM owners WHERE id = :id"), {"id": ids["owners"]})
    assert exc.value.orig.diag.constraint_name == f"fk_{child}_owner_id_owners"  # type: ignore[union-attr]


@pytest.mark.parametrize(
    ("parent", "child"),
    [
        ("owners", "users"),
        ("owners", "guests"),
        ("users", "sessions"),
        ("users", "oauth_accounts"),
        ("chats", "messages"),
    ],
)
def test_delete_cascades(conn: Connection, parent: str, child: str) -> None:
    ids = insert_chain(conn, child)
    conn.execute(text(f"DELETE FROM {parent} WHERE id = :id"), {"id": ids[parent]})
    remaining = conn.execute(
        text(f"SELECT count(*) FROM {child} WHERE id = :id"), {"id": ids[child]}
    )
    assert remaining.scalar_one() == 0
